import { expect, test } from '@playwright/test';

test('catalog filtering, navigation, and mobile layout', async ({ page }) => {
  await page.goto('/');
  await expect(page.getByRole('heading', { name: 'Problem library', exact: true })).toBeVisible();
  await expect(page.locator('.problem-table tbody tr')).toHaveCount(20);
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'light');
  await page.screenshot({ path: '../artifacts/library-light.png', fullPage: true });
  await page.getByRole('button', { name: 'Switch to dark theme' }).click();
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark');
  await page.reload();
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark');
  await expect(page.locator('.problem-table tbody tr')).toHaveCount(20);
  await expect(page.locator('.catalog-footer')).toContainText('100 case studies');
  await page.screenshot({ path: '../artifacts/library-dark.png', fullPage: true });
  await page.getByRole('button', { name: 'Switch to light theme' }).click();
  const caseNumbers = await page.locator('.problem-number').allTextContents();
  for (let current = 2; current <= 5; current++) {
    await page.getByRole('button', { name: 'Next page', exact: true }).click();
    await expect(page).toHaveURL(`/?page=${current}`);
    await expect(page.locator('.problem-table tbody tr')).toHaveCount(20);
    await expect(page.locator('.problem-number').first()).toHaveText(`${(current - 1) * 20 + 1}.`);
    caseNumbers.push(...await page.locator('.problem-number').allTextContents());
  }
  expect(new Set(caseNumbers).size).toBe(100);
  await expect(page.getByRole('button', { name: 'Next page', exact: true })).toBeDisabled();
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: '../artifacts/library-expanded-mobile.png', fullPage: true, animations: 'disabled' });
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.getByRole('link', { name: /The waitlist that skips its turn/ }).click();
  await expect(page.getByRole('heading', { name: 'The waitlist that skips its turn', exact: true })).toBeVisible();
  await expect(page.locator('.monaco-editor')).toBeVisible();
  await page.goBack();
  await expect(page).toHaveURL('/?page=5');
  await page.getByLabel('Search case studies').fill('overflow');
  await expect(page).not.toHaveURL(/page=5/);
  await expect(page.getByRole('link', { name: /Two billion and counting/ })).toBeVisible();
  await expect(page.getByRole('link', { name: /One item short/ })).toHaveCount(0);
  await page.getByRole('button', { name: 'Reset filters' }).click();
  await page.getByLabel('Language filter').selectOption('go');
  await expect(page.locator('.problem-table tbody tr')).toHaveCount(18);
  await page.getByRole('link', { name: 'Start a case', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'One item short', exact: true })).toBeVisible();
  await expect(page.locator('.monaco-editor')).toBeVisible();
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'light');
  await page.getByRole('button', { name: 'Switch to dark theme' }).click();
  await expect(page.locator('.monaco-editor')).toHaveClass(/vs-dark/);
  await page.screenshot({ path: '../artifacts/workspace-dark.png', fullPage: true });
  await page.getByRole('button', { name: 'Switch to light theme' }).click();
  await expect(page.locator('.monaco-editor')).not.toHaveClass(/vs-dark/);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole('button', { name: 'Open navigation' }).click();
  await page.getByRole('link', { name: 'Getting started' }).click();
  await expect(page.getByRole('heading', { name: 'Find the bug. Build the instinct.' })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
});

test('register, fail, retrieve a hint, fix code, unlock solutions, and persist progress', async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('/register');
  const unique = Date.now().toString(36);
  await page.getByLabel('Username').fill(`browser_${unique}`);
  await page.getByLabel('Email address').fill(`browser_${unique}@example.com`);
  await page.getByLabel('Password', { exact: true }).fill('BrowserTestPassword123!');
  await page.getByRole('button', { name: 'Start your debugging journey' }).click();
  await expect(page).toHaveURL('/');
  await page.getByRole('link', { name: /One item short/ }).click();
  await expect(page.locator('.monaco-editor')).toBeVisible();
  await page.getByRole('button', { name: 'Run code', exact: true }).click();
  await expect(page.locator('.results-summary')).toContainText('Failed', { timeout: 90_000 });
  await page.getByRole('button', { name: 'Run code', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Get hint', exact: true })).toBeEnabled({ timeout: 90_000 });
  await page.getByRole('button', { name: 'Get hint', exact: true }).click();
  await expect(page.getByRole('dialog')).toContainText('From the official docs', { timeout: 90_000 });
  await page.getByRole('button', { name: 'Close hint' }).click();
  // Monaco's native EditContext owns keyboard input; its textarea is an IME fallback.
  await page.locator('.monaco-editor .view-lines').click({ position: { x: 100, y: 35 } });
  await page.keyboard.press('ControlOrMeta+a');
  await page.keyboard.insertText('def solve(data):\n    return sum(data["nums"])\n');
  const submission = page.waitForRequest(request => request.url().endsWith('/api/submissions') && request.method() === 'POST');
  await page.getByRole('button', { name: 'Submit fix', exact: true }).click();
  expect((await submission).postDataJSON().code).toContain('return sum(data["nums"])');
  await expect(page.locator('.success-note')).toContainText('All tests passed', { timeout: 90_000 });
  await page.getByRole('button', { name: 'Solutions', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Behind the fix' })).toBeVisible();
  await page.getByRole('button', { name: 'Share this fix' }).click();
  await expect(page.getByRole('button', { name: 'Make private' })).toBeVisible();
  await page.screenshot({ path: '../artifacts/accepted-workspace.png', fullPage: true });
  await page.getByRole('link', { name: 'My progress', exact: true }).click();
  await expect(page.locator('.stat-card').first()).toContainText('1');
  await page.screenshot({ path: '../artifacts/progress-desktop.png', fullPage: true });
  await page.reload();
  await expect(page.locator('.profile-strip')).toContainText(`browser_${unique}`);
  await expect(page.locator('.stat-card').first()).toContainText('1');
  await page.getByRole('button', { name: 'Edit bio', exact: true }).click();
  await page.getByRole('textbox', { name: 'Your bio' }).fill('Learning to reason about the edge cases.');
  await page.getByRole('button', { name: 'Save', exact: true }).click();
  await expect(page.locator('.profile-strip')).toContainText('Learning to reason about the edge cases.');
  await page.getByRole('button', { name: 'Sign out', exact: true }).click();
  await page.getByRole('link', { name: 'Sign in / Join LeetBug' }).click();
  await page.getByLabel('Email address').fill(`browser_${unique}@example.com`);
  await page.getByLabel('Password', { exact: true }).fill('BrowserTestPassword123!');
  await page.getByRole('button', { name: 'Sign in', exact: true }).click();
  await expect(page).toHaveURL('/');
  await page.getByRole('link', { name: 'My progress', exact: true }).click();
  await expect(page.locator('.profile-strip')).toContainText('Learning to reason about the edge cases.');
  await expect(page.locator('.stat-card').first()).toContainText('1');
  expect(errors).toEqual([]);
});

